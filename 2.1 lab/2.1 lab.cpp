#include <iostream>
using namespace std;
int main()
{
	double x, y, z;
	cout << "Введите x, y, z: ";
	cin >> x >> y >> z;

	// Разница между координатами точки и координатами центра шара
	double dx = x - 3;
	double dy = y - 3;
	double dz = z - 3;

	// Квадрат расстояние до центра шара. Точка внутри или снаружи?
	double d2 = dx * dx + dy * dy + dz * dz;

	// Сумма разниц, нужна для проекции на ось 111. Точка в дырке или нет?
	double s = dx + dy + dz;

	// Расстояние до оси цилиндра нашел по Пифагору - из квадрата расстояния до центра вычитаем квадрат проекции на ось
	double r2 = d2 - s * s / 3;

	// Если растояние больше центра шара
	if (d2 > 2 * 2) {
		cout << "Зона 1";
		return 0;
	}
	// Расстояние до оси меньше радиуса цилиндра
	else if (r2 < 0.5 * 0.5) {
		cout << "Зона 3";
		return 0;
	}
	// Внутри шара не в дырке
	else {
		cout << "Зона 2";
		return 0;
	}
}